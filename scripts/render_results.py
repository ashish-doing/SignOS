"""Renders results/*.json into docs/results.md. Numbers are never hand-typed."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"


def load(n):
    p = R / n
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def main():
    L = ["# Track A results (generated by scripts/render_results.py - do not edit)", ""]
    lat = load("latency_local.json")
    L += ["## Latency (MEASURED-LOCAL)"]
    if lat:
        L += [f"{lat['platform']} | Python {lat['python']} | mediapipe {lat['mediapipe']} | {lat['frames']} frames, "
              f"{lat['pipeline_fps']} fps, hand present {lat['hand_present_frac']:.0%}", "", lat["definition"], "",
              "| stage | n | P50 ms | P95 ms | max ms |", "|---|---|---|---|---|"]
        for k in ("camera_to_landmark_ms", "camera_to_landmark_ms_hand_present", "landmark_to_intent_ms",
                  "landmark_to_intent_ms_emitting_frames", "total_ms"):
            v = lat.get(k)
            if v:
                L.append(f"| {k} | {v['n']} | {v['p50']} | {v['p95']} | {v['max']} |")
    else:
        L.append("not run")
    fp = load("fp_rate.json")
    L += ["", "## False positives during natural use (MEASURED-LOCAL)"]
    if fp:
        L += [f"{fp['minutes']} min, hand present {fp['hand_present_frac']:.0%}, valid={fp['valid']}: "
              f"{fp['events_total']} action-worthy events ({fp['events_per_min']}/min) {fp['by_intent']}"]
        if fp["upper95_per_min_if_zero"] is not None:
            L.append(f"0 events observed -> ~95% upper bound {fp['upper95_per_min_if_zero']}/min (rule of three)")
    else:
        L.append("not run")
    ev = load("isl_eval.json")
    L += ["", "## ISL classifier (MEASURED-LOCAL)"]
    if ev:
        L += [f"split: {ev['split']} | train {ev['n_train']} / test {ev['n_test']} | test acc {ev['test_acc']:.3f}",
              f"caveats: {ev['caveats'] or 'none'}", "", "| class | precision | recall | F1 | support |", "|---|---|---|---|---|"]
        for c in ev["classes"]:
            r = ev["report"][c]
            L.append(f"| {c} | {r['precision']:.2f} | {r['recall']:.2f} | {r['f1-score']:.2f} | {int(r['support'])} |")
        L += ["", "confusion matrix (rows true, cols pred): " + json.dumps(ev["confusion_matrix"])]
    else:
        L.append("not run")
    L += ["", "## AI Hub (MEASURED-AIHUB)"]
    found = False
    for p in sorted(R.glob("aihub_*.json")):
        d = json.loads(p.read_text(encoding="utf-8"))
        found = True
        summ = (d.get("profile") or {}).get("execution_summary", {})
        L.append(f"- {d['model']} on {d.get('device_resolved', d['device_requested'])}: status {d['status']}; "
                 f"compile {d.get('compile_job_url')}; profile {d.get('profile_job_url')}; "
                 f"estimated_inference_time (raw field) {summ.get('estimated_inference_time')}; {d.get('error', '')}")
    for p in sorted(R.glob("aihub_*.log")):
        found = True
        L.append(f"- console log: results/{p.name}")
    if not found:
        L.append("not run")
    L += ["", "## QDC (MEASURED-QDC)", "not run" if not list(R.glob("qdc_*")) else "see results/qdc_*"]
    (ROOT / "docs" / "results.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote docs/results.md")


if __name__ == "__main__":
    main()